#!/usr/bin/env python3
"""The IRX part of build.ninja: split, compile, link, pack and verify each module.

configure.py calls write(). The IOP modules have their own compiler, linker
script and container, and nothing in them touches the ELF build.
"""
from __future__ import annotations

import hashlib
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "tools"))
import irx_config  # noqa: E402

TOOLS = Path("tools")
IOP_DIR = TOOLS / "compilers" / "iop-gcc2.8.1" / "lib" / "gcc-lib" / "mipsel-scei-elfl" / "2.8.1"
CPP = IOP_DIR / "cpp"
CC1 = IOP_DIR / "cc1"
IOP_AS = IOP_DIR / "as"
LD = TOOLS / "bin" / "mips-ps2-decompals-ld"

# What the iop-gcc driver's specs pass to cpp for this target.
CPP_DEFINES = [
    "-D__GNUC__=2", "-D__GNUC_MINOR__=8", "-Dmips", "-DMIPSEL", "-D_MIPSEL",
    "-D__mips__", "-D__MIPSEL__", "-D__mips", "-D__MIPSEL", "-D__R3000__",
    "-D__LANGUAGE_C", "-D_LANGUAGE_C", "-DLANGUAGE_C", "-D__OPTIMIZE__",
]

LINKER_SCRIPT = """/* Generated by tools/irx_build.py; do not edit.
 *
 * The module is linked at 0 and the loader relocates it. _gp sits 0x7ff0 past
 * the end of .data, where .sdata would start, which is where .iopmod puts it.
 */
OUTPUT_FORMAT("elf32-littlemips")
OUTPUT_ARCH(mips)
ENTRY(%(entry)s)
%(moduleinfo)sSECTIONS
{
    . = 0x00000000;
    .text   ALIGN(16) : { *(.text) *(.text.*) }
    .rodata ALIGN(16) : { *(.rodata) *(.rodata.*) }
    .data   ALIGN(16) : { *(.data) *(.data.*) }
    _gp = . + 0x7ff0;
    .sdata  ALIGN(16) : { *(.sdata) *(.sdata.*) }
    .sbss   ALIGN(4) (NOLOAD) : { *(.sbss) *(.sbss.*) *(.scommon) }
    .bss    ALIGN(16) (NOLOAD) : { *(.bss) *(.bss.*) *(COMMON) }
    /DISCARD/ : {
        *(.pdr) *(.mdebug*) *(.comment) *(.gnu.attributes) *(.reginfo)
        *(.note*) *(.options)
    }
}
"""

INCLUDE_ASM_LINE = re.compile(r'^\s*INCLUDE_ASM\("[^"]+",\s*([A-Za-z_.][\w.]*)\s*\)')
INCLUDE_RODATA_LINE = re.compile(r'^\s*INCLUDE_RODATA\("[^"]+",\s*(\w+)\s*\)', re.M)
HEADERS = ["include/irx/irx.h", "include/irx/iop.h", "include/irx/spu2.h", "include/irx/sdfsnd.h"]
SPLIT_INPUTS = [TOOLS / "irx_split.py", TOOLS / "irx.py"]


def sha1(path: Path) -> str:
    return hashlib.sha1(path.read_bytes()).hexdigest()


def chunks(cfg: dict) -> list[str]:
    """The .text chunks in link order: the C files' INCLUDE_ASM lines."""
    return [m[1] for src in cfg["paths"]["srcs"]
            for m in (INCLUDE_ASM_LINE.match(l) for l in (ROOT / src).read_text().splitlines()) if m]


def split_digest(cfg: dict) -> str:
    h = hashlib.sha1()
    for p in [irx_config.path(cfg, "target"), irx_config.path(cfg, "symbols")] + [ROOT / p for p in SPLIT_INPUTS]:
        h.update(p.read_bytes())
    return h.hexdigest()


def split(cfg: dict) -> None:
    """Run tools/irx_split.py when the module or its symbols changed."""
    stamp = irx_config.path(cfg, "build") / "split.digest"
    digest = split_digest(cfg)
    if stamp.exists() and stamp.read_text().strip() == digest and (irx_config.path(cfg, "asm") / "text").is_dir():
        return
    subprocess.run([sys.executable, str(ROOT / TOOLS / "irx_split.py"), cfg["key"]], check=True)
    stamp.write_text(digest + "\n")


def write_c(cfg: dict) -> None:
    """Bootstrap a module's C file from the split's chunk order: every chunk INCLUDE_ASM."""
    src = irx_config.path(cfg, "src")
    if src.exists():
        return
    order = irx_config.path(cfg, "build") / "text_order.txt"
    names = [l.strip() for l in order.read_text().splitlines() if l.strip() and not l.startswith("#")]
    src = ROOT / "src" / "irx" / cfg["version"] / f"{cfg['module_dir']}.c"
    src.parent.mkdir(parents=True, exist_ok=True)
    src.write_text('#include "irx.h"\n\n' + "".join(f'INCLUDE_ASM("{cfg["module_dir"]}", {c});\n' for c in names))
    cfg["paths"]["src"] = str(src.relative_to(ROOT))
    cfg["paths"]["srcs"] = [cfg["paths"]["src"]]
    print(f"wrote {cfg['paths']['src']}")


def write_rules(n, prefix: str) -> None:
    n.rule("iopas", f"{prefix}{IOP_AS} -EL -G 0 -I. -o $out $in", description="iop-as $in")
    n.rule("iopcc",
           f"{prefix}{CPP} -lang-c {' '.join(CPP_DEFINES)} -DASM_ROOT=\\\"$asm_root\\\" -D$version_define -Iinclude/irx $in $out.i && "
           f"{prefix}{CC1} -quiet -O2 -G 0 $out.i -o $out.s && "
           f"{prefix}{IOP_AS} -EL -G 0 -I. -o $out $out.s",
           description="iop-gcc $in")
    n.rule("iopld", f"{LD} -EL -T $script --emit-relocs -o $out $in", description="ld $out")
    n.rule("irxpack", f"{sys.executable} {TOOLS}/irx.py pack $in -o $out --name=$name --version $version",
           description="pack $out")
    n.rule("irxverify", f"{sys.executable} {TOOLS}/irx_verify.py $in $orig && touch $out",
           description="verify $orig")
    n.newline()


def write(n, versions: list[str], prefix: str) -> tuple[list[str], list[str]]:
    """Add every module of `versions` whose retail file is in orig/.

    Returns the phony targets (`<version>-irx`) and the configure inputs.
    """
    for tool in (CPP, CC1, IOP_AS):
        if not (ROOT / tool).exists():
            sys.exit(f"{tool} missing; run tools/download_tools.py")
    write_rules(n, prefix)
    targets, inputs = [], [str(TOOLS / "irx_build.py")]
    for version in versions:
        stamps = []
        for key in irx_config.modules(version):
            cfg = irx_config.load(key)
            module = cfg["module_dir"]
            target = irx_config.path(cfg, "target")
            yaml = f"config/{version}/irx/{module}/{module}.yaml"
            inputs += [yaml, cfg["paths"]["symbols"]]
            if not target.exists():
                print(f"{cfg['paths']['target']} missing; {key} not built (tools/extract.py)")
                continue
            if sha1(target) != cfg["sha1"]:
                sys.exit(f"{cfg['paths']['target']}: sha1 is not {cfg['sha1']} from {yaml}")
            b = Path(cfg["paths"]["build"])
            (ROOT / b).mkdir(parents=True, exist_ok=True)
            split(cfg)
            write_c(cfg)
            inputs += cfg["paths"]["srcs"]
            script = b / "link.ld"
            # A module without a moduleinfo block (sdfprint) carries 0xFFFFFFFF in .iopmod.
            info = cfg["module"].get("moduleinfo")
            ld = LINKER_SCRIPT % {"entry": cfg["module"]["entry"],
                                  "moduleinfo": "" if info is None else f"_irx_id = {info:#x};\n"}
            if not (ROOT / script).exists() or (ROOT / script).read_text() != ld:
                (ROOT / script).write_text(ld)

            asm = Path(cfg["paths"]["asm"])
            deps = [str(asm / "text" / f"{c}.s") for c in chunks(cfg)]
            # Once the C files place .rodata piece by piece, rodata.s is not linked.
            pieces = [p for src in cfg["paths"]["srcs"] for p in INCLUDE_RODATA_LINE.findall((ROOT / src).read_text())]
            deps += [str(asm / "rodata" / f"{p}.s") for p in pieces]
            headers = [h for h in HEADERS + [f"include/irx/{module}.h"] if (ROOT / h).exists()]
            objs = []
            for src in cfg["paths"]["srcs"]:
                stem = Path(src).stem
                asmcheck = b / f"{stem}.asmcheck.stamp"
                n.build(str(asmcheck), "asmcheck", [src],
                        implicit=["tools/check_inline_asm.py", "config/inline_asm_allow.txt"])
                objs.append(str(b / f"{stem}.o"))
                n.build(objs[-1], "iopcc", [src], implicit=deps + headers + [str(asmcheck)],
                        variables={"asm_root": cfg["paths"]["asm_root"],
                                   "version_define": f"VERSION_{version.upper()}"})
            for part in ("data", "bss") if pieces else ("rodata", "data", "bss"):
                part_src = asm / f"{part}.s"
                if (ROOT / part_src).exists() and (ROOT / part_src).stat().st_size:
                    n.build(str(b / f"{part}.o"), "iopas", [str(part_src)])
                    objs.append(str(b / f"{part}.o"))
            elf = b / f"{module}.elf"
            n.build(str(elf), "iopld", objs, implicit=[str(script)], variables={"script": str(script)})
            built = b.parent / f"{module}.IRX"
            n.build(str(built), "irxpack", [str(elf)], implicit=[str(TOOLS / "irx.py")],
                    variables={"name": cfg["module"]["name"], "version": str(cfg["module"]["version"])})
            stamp = b.parent / f"{module}.ok"
            n.build(str(stamp), "irxverify", [str(built)],
                    implicit=[cfg["paths"]["target"], str(TOOLS / "irx_verify.py")],
                    variables={"orig": cfg["paths"]["target"]})
            stamps.append(str(stamp))
        if stamps:
            n.build(f"{version}-irx", "phony", stamps)
            targets.append(f"{version}-irx")
        n.newline()
    return targets, inputs
