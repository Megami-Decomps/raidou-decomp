#!/usr/bin/env python3
"""Write symbol_addrs.txt for an IRX module that has no IDB: python tools/irx_scan.py raidou1/SDRDRV

Bounds come from a linear walk of .text; import stubs are named from an ordinal
table. Names already in the file at the same address are kept on a rescan.
"""
from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

import rabbitizer

sys.path.insert(0, str(Path(__file__).resolve().parent))
import irx  # noqa: E402
import irx_config  # noqa: E402
from irx_split import load_syms  # noqa: E402

IMPORT_MAGIC, EXPORT_MAGIC = 0x41E00000, 0x41C00000
JR_RA = 0x03E00008
DEFAULT_IMPORTS = Path.home() / "projects/ps2-split/ps2split/formats/iop_imports.tsv"


def load_import_names(path: Path) -> dict[tuple[str, int], str]:
    names = {}
    if not path.exists():
        return names
    for line in path.read_text().splitlines():
        cols = line.split("\t")
        if len(cols) >= 3 and cols[1].isdigit():
            names[(cols[0], int(cols[1]))] = cols[2]
    return names


def words(text: irx.Section) -> list[int]:
    return list(struct.unpack_from(f"<{len(text.data) // 4}I", text.data))


def tables(text: irx.Section, w: list[int], import_names) -> tuple[list, list, set]:
    """Import stubs as (addr, name, size), table spans as (start, stop), export targets."""
    stubs, spans, exports = [], [], set()
    relocs = set(text.relocs)
    i = 0
    while i < len(w):
        if w[i] in (IMPORT_MAGIC, EXPORT_MAGIC) and i + 5 <= len(w) and w[i + 1] == 0:
            lib = text.data[(i + 3) * 4:(i + 5) * 4].split(b"\0")[0].decode("ascii")
            start = i
            i += 5
            if w[start] == IMPORT_MAGIC:
                while i + 1 < len(w) and w[i] == JR_RA and w[i + 1] >> 16 == 0x2400:
                    ordinal = w[i + 1] & 0xFFFF
                    name = import_names.get((lib, ordinal), str(ordinal))
                    stubs.append((text.addr + i * 4, f"{lib}_{name}", 8))
                    i += 2
            else:
                # The terminator is the first word without a relocation: an
                # export of the function at 0 is a zero word too.
                while i < len(w) and (i * 4, irx.R_MIPS_32) in relocs:
                    exports.add(w[i])
                    i += 1
            i += 2 if w[start] == IMPORT_MAGIC else 1
            spans.append((text.addr + start * 4, text.addr + i * 4))
        else:
            i += 1
    return stubs, spans, exports


def scan(module: irx.Module, import_names) -> list[tuple[int, str, int]]:
    text = module.section(".text")
    w = words(text)
    stubs, spans, exports = tables(text, w, import_names)
    covered = set()
    for a, b in spans:
        covered.update(range(a, b, 4))
    starts = {module.entry} | exports
    for k, word in enumerate(w):
        ins = rabbitizer.Instruction(word, text.addr + k * 4)
        if ins.uniqueId == rabbitizer.InstrId.cpu_jal:
            starts.add(ins.getInstrIndexAsVram())

    funcs = []
    addr, end = text.addr, text.addr + text.size
    while addr < end:
        if addr in covered or w[(addr - text.addr) // 4] == 0:
            addr += 4
            continue
        start, reach = addr, addr
        while addr < end and addr not in covered:
            if addr != start and addr in starts:
                break
            word = w[(addr - text.addr) // 4]
            ins = rabbitizer.Instruction(word, addr)
            if ins.isBranch() and not ins.isJumpWithAddress():
                reach = max(reach, addr + ins.getBranchOffsetGeneric())
            if word == JR_RA and addr >= reach:
                addr += 8
                break
            addr += 4
        funcs.append((start, f"func_{start:08X}", addr - start))
    return sorted(funcs + stubs)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("modules", nargs="+")
    ap.add_argument("--imports", type=Path, default=DEFAULT_IMPORTS)
    args = ap.parse_args()
    import_names = load_import_names(args.imports)
    for key in [k for m in args.modules for k in irx_config.resolve(m)]:
        cfg = irx_config.load(key)
        module = irx.read(irx_config.path(cfg, "target"))
        path = irx_config.path(cfg, "symbols")
        kept = {a: n for a, n, _s, _k in load_syms(cfg)} if path.exists() else {}
        rows = scan(module, import_names)
        if module.entry not in {a for a, _n, _s in rows}:
            raise SystemExit(f"{key}: entry {module.entry:#x} is not a function start")
        lines = ["// Generated by tools/irx_scan.py from the module (no IDB); names kept on rescan."]
        for a, n, s in rows:
            n = kept.get(a, n)
            lines.append(f"{n} = 0x{a:08X}; // type:func size:0x{s:X}")
        lines += [f"{n} = 0x{a:08X};" for a, n in sorted(kept.items())
                  if a not in {r[0] for r in rows}]
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(lines) + "\n")
        print(f"{path.relative_to(irx_config.ROOT)}: {len(rows)} functions")


if __name__ == "__main__":
    main()
