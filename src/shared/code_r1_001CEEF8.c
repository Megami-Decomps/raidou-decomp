s32 GetTblIndex(s32 EventNo) {
    u32 i;

    if (TmxPreLoadPID == NULL) {
        return -1;
    }
    dds3GetProcessData(TmxPreLoadPID);
    for (i = 0; i < 27; i++) {
        if (EventNo == GetTblIndexData[i].eventNo) {
            return i;
        }
    }
    return -1;
}

